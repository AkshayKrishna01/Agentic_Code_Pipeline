from typing import Optional, TypedDict 
from datetime import datetime
from pydantic import BaseModel, field_validator,ConfigDict


#description:Represents structured error details with message and timestamp.
class Error(BaseModel):
    error: str
    timestamp: datetime


#description:Defines the standard API response structure for all endpoints.

class APIResponse(BaseModel):
    status_code: int
    status: str
    message: str
    data: Optional[object]
    error: Optional[Error]
    request_id: str

    model_config = ConfigDict(
        exclude_none=True   
    )



#description: validates incoming pipeline request with user query and user ID.
class PipelineRequest(BaseModel):
    user_query: str
    user_id: str

    @field_validator("user_query")
    def validate_user_query(cls, v: str):
        if not isinstance(v, str) or not v.strip():
            raise ValueError("user_query is required and must be a non-empty string")
        return v.strip()
    
    @field_validator("user_id")
    def validate_user_query(cls, v: str):
        if not isinstance(v, str) or not v.strip():
            raise ValueError("user_id is required and must be a non-empty string")
        return v.strip()


#description: defines structured output data containing generated code and timestamp.
class PipelineResponseData(BaseModel):
    output: str
    timestamp: datetime



#description extends APIResponse to enforce typed pipeline response data.
class PipelineResponse(APIResponse):
    data: Optional[PipelineResponseData]
    model_config = ConfigDict(
        exclude_none=True   
    )


#description Represents the internal state passed between nodes in the LangGraph workflow.
class AgentState(TypedDict):
    user_query: str
    code: Optional[str]
    context: Optional[str]
    review: Optional[str]
    status: Optional[str]
    route: Optional[str]
    retries: int
    thread_id: str























